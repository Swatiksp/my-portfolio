const STEPS = GROUPS.flatMap((group) => group.steps);
const HOLD = 0.58;

function ease(x: number) {
  const t = Math.min(1, Math.max(0, x));
  return t < 0.5 ? 2 * t * t : 1 - ((-2 * t + 2) ** 2) / 2;
}

function mix(local: number) {
  if (local <= HOLD) return 0;
  return ease((local - HOLD) / (1 - HOLD));
}

function frameAt(progress: number) {
  const scaled = Math.min(STEPS.length - 0.0001, Math.max(0, progress) * STEPS.length);
  const index = Math.floor(scaled);
  const local = scaled - index;
  const t = index >= STEPS.length - 1 ? 0 : mix(local);
  return { index, t };
}

function shift(i: number, index: number, amount: number, distance: number) {
  if (i === index) {
    return { opacity: 1 - amount, transform: `translate3d(0, ${-distance * amount}px, 0)` };
  }
  if (i === index + 1) {
    return { opacity: amount, transform: `translate3d(0, ${distance * (1 - amount)}px, 0)` };
  }
  return { opacity: 0, transform: `translate3d(0, ${distance}px, 0)`, visibility: "hidden" as const };
}

export function HaloHifiStages() {
  const root = useRef<HTMLDivElement>(null);
  const [progress, setProgress] = useState(0);
  const { index, t } = frameAt(progress);
  const bodyT = t <= 0.16 ? 0 : ease((t - 0.16) / 0.84);

  const jumpTo = (step: number) => {
    const el = root.current;
    const panel = el?.firstElementChild as HTMLElement | null;
    if (!el || !panel) return;
    const start = el.getBoundingClientRect().top + window.scrollY;
    const travel = Math.max(1, el.offsetHeight - panel.offsetHeight);
    const next = start - CHROME + ((step + 0.22) / STEPS.length) * travel;
    window.scrollTo({ top: next, behavior: "smooth" });
  };

  useEffect(() => {
    const onScroll = () => {
      const el = root.current;
      const panel = el?.firstElementChild as HTMLElement | null;
      if (!el || !panel) return;
      const reduce = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
      const start = el.getBoundingClientRect().top + window.scrollY;
      const travel = Math.max(1, el.offsetHeight - panel.offsetHeight);
      const scrolled = window.scrollY + CHROME - start;
      const next = Math.min(1, Math.max(0, scrolled / travel));
      setProgress(reduce ? (next > 0.5 ? 1 : 0) : next);
    };
    onScroll();
    window.addEventListener("scroll", onScroll, { passive: true });
    window.addEventListener("resize", onScroll);
    return () => {
      window.removeEventListener("scroll", onScroll);
      window.removeEventListener("resize", onScroll);
    };
  }, []);

  let cursor = 0;

  return (
    <div ref={root} className="w-full" style={{ height: `calc(100vh - ${CHROME}px + ${(STEPS.length - 1) * 52}vh)` }}>
      <div className="sticky flex items-center" style={{ top: CHROME, height: `calc(100vh - ${CHROME}px)` }}>
        <div className="flex w-full flex-col" style={{ gap: 28 }}>
          <div
            className="flex w-full items-center max-lg:flex-col max-lg:items-start lg:w-[calc(100%+5rem)]"
            style={{ gap: 16 }}
          >
            <div className="grid shrink-0" style={{ width: "min(100%, 200px)" }}>
              {STEPS.map((step, i) => {
                const header = shift(i, index, t, 18);
                const body = shift(i, index, bodyT, 26);
                return (
                  <div key={step.id} className="flex flex-col" style={{ gridArea: "1 / 1", gap: 20, pointerEvents: "none" }}>
                    <div className="flex flex-col" style={{ gap: 8, ...header }}>
                      <p
                        className="m-0"
                        style={{
                          fontFamily: SANS,
                          fontWeight: 600,
                          fontSize: 12,
                          lineHeight: "16px",
                          letterSpacing: "1.44px",
                          textTransform: "uppercase",
                          color: FOREST,
                        }}
                      >
                        {step.stage}
                      </p>
                      <h2
                        className="m-0"
                        style={{
                          fontFamily: "'Newsreader', 'Iowan Old Style', Georgia, serif",
                          fontWeight: 400,
                          fontSize: 40,
                          lineHeight: "44px",
                          letterSpacing: "-0.02em",
                          color: INK,
                        }}
                      >
                        {step.title}
                      </h2>
                    </div>
                    <div className="flex flex-col" style={{ gap: 16, ...body }}>
                      {step.paragraphs.map((paragraph) => (
                        <p key={paragraph} className="m-0" style={copy}>
                          {paragraph}
                        </p>
                      ))}
                    </div>
                  </div>
                );
              })}
            </div>

            <div
              className="relative min-w-0"
              style={{ flex: "1 1 820px", filter: "drop-shadow(0px 4px 10px rgba(0,0,0,0.18))" }}
            >
              <img src={macbook} alt="" className="block w-full h-auto" />
              {STEPS.map((step, i) => {
                const screen = shift(i, index, t, 0);
                return (
                  <img
                    key={step.id}
                    src={step.src}
                    alt={screen.opacity > 0.5 ? step.alt : ""}
                    className="absolute object-cover object-center"
                    style={{
                      left: "11.68%",
                      top: "2.58%",
                      width: "76.64%",
                      height: "84.54%",
                      borderTopLeftRadius: 6,
                      borderTopRightRadius: 6,
                      opacity: screen.opacity,
                      visibility: screen.visibility,
                    }}
                  />
                );
              })}
            </div>
          </div>

          <div className="flex w-full justify-center" style={{ gap: 10 }} role="group" aria-label="Stage progress">
            {GROUPS.map((group) => {
              const start = cursor;
              cursor += group.steps.length;
              return (
                <div
                  key={group.id}
                  className="flex overflow-hidden"
                  style={{ height: 10, borderRadius: 99, background: TRACK, width: group.steps.length * 34 }}
                >
                  {group.steps.map((step, si) => {
                    const stepIndex = start + si;
                    const amount = stepIndex <= index ? 1 : stepIndex === index + 1 ? t : 0;
                    return (
                      <button
                        key={step.id}
                        type="button"
                        aria-label={step.stage}
                        aria-current={amount > 0.55 ? "step" : undefined}
                        onClick={() => jumpTo(stepIndex)}
                        className="h-full border-none p-0 cursor-pointer"
                        style={{
                          flex: 1,
                          background: `linear-gradient(to right, ${FOREST} ${amount * 100}%, ${TRACK} ${amount * 100}%)`,
                          boxShadow: si < group.steps.length - 1 ? "inset -3px 0 0 #ffffff" : undefined,
                        }}
                      />
                    );
                  })}
                </div>
              );
            })}
          </div>
        </div>
      </div>
    </div>
  );
}

const copy = {
  fontFamily: SANS,
  fontWeight: 400,
  fontSize: 18,
  lineHeight: "28px",
  color: INK,
} as const;
